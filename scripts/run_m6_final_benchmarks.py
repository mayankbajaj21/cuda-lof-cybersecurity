"""
run_m6_final_benchmarks.py — Milestone M6: Final Benchmarks and Scalability Analysis

Real, measured CPU vs. naive-CUDA vs. optimized-CUDA comparison, extending the
M4 (profiling) and M5 (optimization) work on this machine's RTX 4050 Laptop
GPU (sm_89, 6GB VRAM) and host (16.4GB RAM, ~5.2GB available at run time).

Before running anything, a dynamic memory-feasibility check decides which
candidate dataset sizes can actually be benchmarked without exceeding
available VRAM/RAM. Nothing here is faked: infeasible sizes are marked
UNAVAILABLE with an explicit reason rather than estimated or skipped silently.

NOTE ON DATA PROVENANCE: on this machine, data/raw/ contains no real CICIDS2017
CSVs; the "full" processed dataset (data/processed/cicids2017_clean_full.npz,
1,000,000 rows) and all stratified subsets were generated by preprocessing/
prepare_dataset.py from a synthetic CICIDS2017-shaped placeholder dataset
(file name: synthetic_cicids2017.csv, per data/processed/dataset_metadata.json).
This does not affect the validity of the timing/memory-scalability findings
below, which depend only on row count (N) and feature count (D=68), not on
whether feature values are real or synthetic traffic statistics. It does mean
"full dataset" here is 1,000,000 rows, not the 2,520,798-row real CICIDS2017
figure quoted elsewhere in this repo's documentation (a different machine's
M1 run, per earlier milestones).
"""

