"""Regenerate the M8 results table in README.md from
results/m8_advanced_optimizations/variant_benchmarks.csv.

Only the text between <!-- M8_TABLE_START --> and <!-- M8_TABLE_END --> is
replaced. Exits non-zero (and changes nothing) if the markers or the CSV are
missing, so hand-typed numbers can't silently drift from the measured data.

Usage: python scripts/update_readme_tables.py
"""

import os
import sys

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
README = os.path.join(ROOT, "README.md")
CSV = os.path.join(ROOT, "results", "m8_advanced_optimizations", "variant_benchmarks.csv")
START = "<!-- M8_TABLE_START -->"
END = "<!-- M8_TABLE_END -->"

SOURCE_LABELS = {
    "cpu": "CPU reference",
    "baseline": "GPU baseline",
    "syllabus": "Syllabus",
    "outside_syllabus": "Outside syllabus",
    "combined_outside_syllabus": "Outside syllabus (combined)",
}
LADDER = [-1, 0, 1, 2, 3, 4, 5]


def _x(v, digits=2):
    return "–" if pd.isna(v) else f"{v:.{digits}f}×"


def build_tables(df):
    out = []
    order = df.drop_duplicates("subset").sort_values("n_samples")["subset"]
    for subset in order:
        sub = df[df["subset"] == subset].copy()
        sub["pos"] = sub["variant_id"].map(LADDER.index)
        sub = sub.sort_values("pos")
        out.append(f"**{subset}**\n")
        out.append("| Variant | Source | Exact / approx. | Median end-to-end | × vs CPU | × vs V0 | × vs V1 | Peak GPU memory |")
        out.append("| :--- | :--- | :---: | ---: | ---: | ---: | ---: | ---: |")
        for _, r in sub.iterrows():
            src = SOURCE_LABELS.get(r["technique_source"], r["technique_source"])
            if r["classification"] != "MEASURED":
                out.append(f"| {r['variant_name']} | {src} | {r['exact_or_approximate']} | "
                           f"not run — {r['unavailable_reason']} | – | – | – | – |")
                continue
            mem = "–" if pd.isna(r["peak_gpu_mem_bytes_tracked"]) else f"{r['peak_gpu_mem_bytes_tracked'] / 2**20:,.0f} MiB"
            out.append(
                f"| {r['variant_name']} | {src} | {r['exact_or_approximate']} | {r['end_to_end_median_ms']:,.2f} ms | "
                f"{_x(r['speedup_vs_cpu'], 1)} | {_x(r['speedup_vs_v0'])} | {_x(r['speedup_vs_v1'])} | {mem} |"
            )
        out.append("")
    out.append("_Generated by `scripts/update_readme_tables.py` from "
               "`results/m8_advanced_optimizations/variant_benchmarks.csv` — do not edit by hand._")
    return "\n".join(out)


def main():
    if not os.path.isfile(CSV):
        sys.exit(f"ERROR: {CSV} not found — run scripts/run_m8_advanced_optimizations.py first.")
    with open(README, "r", encoding="utf-8") as f:
        text = f.read()
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        sys.exit(f"ERROR: README.md must contain exactly one {START} followed by one {END}.")
    table = build_tables(pd.read_csv(CSV))
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new_text = f"{head}{START}\n{table}\n{END}{tail}"
    with open(README, "w", encoding="utf-8") as f:
        f.write(new_text)
    print(f"Updated M8 table in {README}")


if __name__ == "__main__":
    main()
